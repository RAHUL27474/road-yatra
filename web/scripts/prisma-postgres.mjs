// Writes prisma/schema.postgres.prisma from prisma/schema.prisma with the datasource switched to PostgreSQL.
// Local development uses SQLite (schema.prisma); the live site on Vercel uses Postgres (Neon).
// Env on Vercel: DATABASE_URL (pooled) and DATABASE_URL_UNPOOLED (direct), as set by the Neon integration.
import fs from "node:fs";

const src = fs.readFileSync("prisma/schema.prisma", "utf8");
const pg = src.replace(
  /datasource db \{[\s\S]*?\n\}/,
  `datasource db {
  provider  = "postgresql"
  url       = env("DATABASE_URL")
  directUrl = env("DATABASE_URL_UNPOOLED")
}`,
);
if (pg === src) throw new Error("Could not find the datasource block in prisma/schema.prisma");
fs.writeFileSync("prisma/schema.postgres.prisma", `// GENERATED by scripts/prisma-postgres.mjs — do not edit, edit schema.prisma instead.\n${pg}`);
console.log("Wrote prisma/schema.postgres.prisma");
